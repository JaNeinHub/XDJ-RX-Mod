// XDJRX-MOD web builder: the build itself.
// Inputs (downloaded by the user from Pioneer/AlphaTheta, never sent anywhere):
//   XDJ-RX_v221.zip (or the XDJRX.UPD inside it)                  -> Pioneer's 2.21 update
//   GPL package 1.50 part .00 zip (or pioneerxdjrx.tar.gz.00)      -> the update key (initramfs/.../aes256.key)
// Outputs: install (XDJRX-MOD), R1 (Pioneer's app archive back), R2 (official 2.21 with release.txt raised).
// Every step is checked against fixed values: the page can only build the hardware-tested archive.
// Needs XRM.hash/aes/inflate/zip/tar/iso/upd, XRM.assets (generated by build.py) and pako.
// SPDX-License-Identifier: GPL-3.0-only
var XRM = typeof XRM !== 'undefined' ? XRM : {};

XRM.build = (function () {
	'use strict';

	// Pioneer's files, identified by size and checked by hash (hashes only: nothing of Pioneer's is in here)
	const PIONEER = {
		fwZip: { size: 48378407, inner: 'XDJRX.UPD' },
		upd: { size: 48363536, sha256: '3a28857c6760a4b96d1b9ccc5a9359ac81a0268789ae0ccc3d179fef64f87c59' },
		gplZip: { size: 208958482, inner: 'pioneerxdjrx.tar.gz.00' },
		gplRaw: { size: 209715200 },
		gplPart01: [73352824, 74170112],	// zip / unzipped part .01: not needed
		keySha256: '791d40e404798d354619f4bc268ac6dfaff6dca97504c6527354dcd8c7362ec7',
		keyMember: 'pioneer_xdj_rx/initramfs.tar.gz',
		keyFile: 'initramfs/usr/local/pioneer/aes256.key',
		stockArchive: { size: 2137610, md5: 'f6848f953bec73978b828be761df4a0c' },
		stockTarMd5: '0743b10668c7d60efb88d7717d37aae7',
		release: '2.21\n',
	};
	const GPL_READ = 24 << 20, GPL_GZ_NEED = 16 << 20, HEAD_BYTES = 65536;	// the key is in the first ~11 MB of the .tar.gz
	const BOOT_LEN = 0x300000;	// what the RX's init reads of the app partition

	// head: the file's first bytes (HEAD_BYTES). Both .00 parts on Pioneer's page (pioneer_xdj_rx and the
	// Freescale BSP L3.0.35_…_source) are exactly 200 MiB when unzipped, so an unzipped part is told apart by
	// the first name in its tar: pioneer_xdj_rx/ (the one with the key) or L3.0.35_4.1.0_130816_source/.
	function firstTarName(gz) {
		try {
			const inf = new pako.Inflate();
			let out = null;
			inf.onData = (c) => { if (!out) out = c; };
			inf.push(gz, false);
			return out && out.length >= 100 ? XRM.hash.text(out.subarray(0, 100)).replace(/\0.*$/, '') : null;
		} catch (e) {
			return null;
		}
	}

	function identify(name, size, head) {
		const zipName = () => {
			try { return XRM.zip.entry(head).name; } catch (e) { return null; }
		};
		const zn = zipName();
		if (size === PIONEER.fwZip.size && zn === PIONEER.fwZip.inner) return 'fw-zip';
		if (size === PIONEER.upd.size) return 'fw-upd';
		if (size === PIONEER.gplZip.size && zn === PIONEER.gplZip.inner) return 'gpl-zip';
		if (zn && /^L3035/.test(zn)) return 'gpl-bsp';	// the Freescale BSP parts or docs, zipped
		if (size === PIONEER.gplRaw.size && head[0] === 0x1f && head[1] === 0x8b) {
			const first = firstTarName(head);
			if (first && first.indexOf('pioneer_xdj_rx/') === 0) return 'gpl-raw';
			if (first && first.indexOf('L3.0.35') === 0) return 'gpl-bsp';
			return null;
		}
		if (PIONEER.gplPart01.indexOf(size) >= 0) return 'gpl-part01';
		return null;
	}

	const fail = (msg) => { throw new Error(msg); };

	function firmware(kind, bytes) {
		let upd = bytes;
		if (kind === 'fw-zip') {
			const e = XRM.zip.entry(bytes);
			if (e.name !== PIONEER.fwZip.inner || e.method !== 8) fail('XDJ-RX_v221.zip: unexpected content');
			upd = pako.inflateRaw(bytes.subarray(e.start, e.start + e.csize));
		}
		if (upd.length !== PIONEER.upd.size || XRM.hash.sha256(upd) !== PIONEER.upd.sha256)
			fail('This is not Pioneer\'s official XDJ-RX 2.21 update (checksum differs).');
		return upd;
	}

	function key(kind, prefix) {
		let gz = prefix;
		if (kind === 'gpl-zip') {
			const e = XRM.zip.entry(prefix);
			if (e.name !== PIONEER.gplZip.inner || (e.method !== 9 && e.method !== 8)) fail('GPL part: unexpected zip content');
			gz = XRM.inflate.inflateRaw(prefix.subarray(e.start), { deflate64: e.method === 9, maxOut: GPL_GZ_NEED }).data;
		}
		// gunzip piece by piece until the initramfs member is complete
		const inf = new pako.Inflate();
		let buf = new Uint8Array(64 << 20), len = 0, found = null;
		inf.onData = (chunk) => {
			if (len + chunk.length > buf.length) {
				const n = new Uint8Array(Math.max(buf.length * 2, len + chunk.length));
				n.set(buf.subarray(0, len));
				buf = n;
			}
			buf.set(chunk, len);
			len += chunk.length;
		};
		const STEP = 1 << 20;
		for (let o = 0; o < gz.length && !found; o += STEP) {
			inf.push(gz.subarray(o, Math.min(o + STEP, gz.length)), false);
			if (inf.err) fail('GPL part: unpacking failed (' + inf.msg + ')');
			const r = XRM.tar.find(buf.subarray(0, len), PIONEER.keyMember);
			if (r.data) found = r.data;
			else if (r.end) break;
		}
		if (!found) fail('GPL part: the key wasn\'t found where expected. Is this XDJ-RX version 1.50, part .00?');
		const keyFile = XRM.tar.file(pako.ungzip(found), PIONEER.keyFile);
		if (XRM.hash.sha256(keyFile) !== PIONEER.keySha256) fail('GPL part: the key file differs from the expected one.');
		return keyFile;
	}

	const A = () => XRM.assets;
	const asc = (s) => XRM.hash.ascii(s);
	const screen = (b64) => pako.inflateRaw(XRM.hash.fromBase64(b64));

	function targetConf(title, archive, accept) {
		return asc('TITLE="' + title + '"\nSIZE=' + archive.length + '\nMD5=' + XRM.hash.md5(archive) +
			'\nACCEPT="' + accept + '"\n');
	}

	function updateImage(archive, conf, screens) {
		const files = [
			{ path: 'update', data: XRM.hash.fromBase64(A().updateScript), mode: 0o100555 },
			{ path: 'images/pioneer.tar.gz', data: archive, mode: 0o100444 },
			{ path: 'images/target.conf', data: conf, mode: 0o100444 },
		];
		for (const [name, b64] of Object.entries(screens)) files.push({ path: 'screens/' + name + '.bin', data: screen(b64), mode: 0o100444 });
		return XRM.iso.build(files, A().release.date, 'XDJRXMOD');
	}

	function readBack(keys, upd) {	// our own file decrypted again: the archive inside and its target.conf
		const { payload } = XRM.upd.split(upd);
		const read = XRM.upd.reader(keys, payload);
		const files = XRM.iso.list(read);
		const get = (p) => { const f = files[p]; if (!f) fail('self-check: ' + p + ' missing'); return read(f.extent * 2048, f.size); };
		return { archive: get('/images/pioneer.tar.gz'), conf: XRM.hash.text(get('/images/target.conf')), update: get('/update') };
	}

	function gzip9(tar) {	// = Python's gzip.compress(tar, 9, mtime=0)
		const d = pako.deflateRaw(tar, { level: 9 });
		const out = new Uint8Array(10 + d.length + 8);
		out.set([0x1f, 0x8b, 8, 0, 0, 0, 0, 0, 2, 0xff]);
		out.set(d, 10);
		const crc = XRM.hash.crc32(tar), n = tar.length >>> 0;
		out.set([crc & 255, crc >>> 8 & 255, crc >>> 16 & 255, crc >>> 24 & 255, n & 255, n >>> 8 & 255, n >>> 16 & 255, n >>> 24 & 255], 10 + d.length);
		return out;
	}

	// The build as separate steps, so the page can update its progress between them.
	function steps(input, opts) {
		const s = { log: [], out: {}, upd: input.upd };
		const r = A().release;
		const note = (m) => s.log.push(m);
		return [
			['Checking the update key', () => {
				s.keys = XRM.upd.loadKey(input.keyFile);
				note('key: from Pioneer\'s GPL package 1.50, SHA-256 ' + PIONEER.keySha256.slice(0, 16) + '... (matches)');
			}],
			['Opening Pioneer\'s 2.21 update', () => {
				const { payload, tag } = XRM.upd.split(input.upd);
				s.tag = tag;
				s.read = XRM.upd.reader(s.keys, payload);
				s.files = XRM.iso.list(s.read);
				const f = s.files['/images/pioneer.tar.gz'];
				if (!f) fail('the update holds no app archive');
				s.stock = s.read(f.extent * 2048, f.size).slice();
				if (s.stock.length !== PIONEER.stockArchive.size || XRM.hash.md5(s.stock) !== PIONEER.stockArchive.md5)
					fail('Pioneer\'s app archive differs from 2.21');
				note('official XDJRX.UPD: tag ' + XRM.hash.text(tag).replace(/\0+$/, '') + ', CRC ok, SHA-256 matches');
				note('stock app archive: ' + s.stock.length + ' bytes, md5 ' + PIONEER.stockArchive.md5);
			}],
			['Adding the mod to the app archive', () => {
				const tar = pako.ungzip(s.stock);
				if (XRM.hash.md5(tar) !== PIONEER.stockTarMd5) fail('stock tar differs');
				const lib = XRM.hash.fromBase64(A().lib);
				if (lib.length !== r.lib.size || XRM.hash.md5(lib) !== r.lib.md5) fail('embedded library damaged');
				const mod = XRM.tar.buildMod(tar, lib, asc(A().aplOld), asc(A().aplNew));
				if (XRM.hash.md5(mod) !== r.modTarMd5) fail('the mod archive came out different from the tested one (tar)');
				s.mod = gzip9(mod);
				if (s.mod.length !== r.modArchive.size || XRM.hash.md5(s.mod) !== r.modArchive.md5)
					fail('the mod archive came out different from the tested one (gzip)');
				if (s.mod.length >= BOOT_LEN) fail('archive too big for the boot loader');
				note('library: ' + lib.length + ' bytes, md5 ' + r.lib.md5 + ' (' + r.libName + ')');
				note('mod app archive: ' + s.mod.length + ' bytes, md5 ' + r.modArchive.md5 + ' (= ' + r.testedAs + ')');
			}],
			['Building the install file', () => {
				const accept = PIONEER.stockArchive.size + ':' + PIONEER.stockArchive.md5;
				const iso = updateImage(s.mod, targetConf(r.name + ': ' + r.title, s.mod, accept),
					Object.assign({}, A().screens.install, A().screens.fail));
				s.out.install = XRM.upd.make(s.keys, iso, s.tag);
				const back = readBack(s.keys, s.out.install);
				if (XRM.hash.md5(back.archive) !== r.modArchive.md5) fail('self-check of the install file failed');
				note('install/XDJRX.UPD: ' + s.out.install.length + ' bytes, md5 ' + XRM.hash.md5(s.out.install));
			}],
			['Building restore file R1', () => {
				const iso = updateImage(s.stock, targetConf(r.name + ' restore R1: Pioneer original pioneer.tar.gz 2.21', s.stock, 'any'),
					Object.assign({}, A().screens.restore, A().screens.fail));
				s.out.r1 = XRM.upd.make(s.keys, iso, s.tag);
				const back = readBack(s.keys, s.out.r1);
				if (XRM.hash.md5(back.archive) !== PIONEER.stockArchive.md5) fail('self-check of R1 failed');
				note('restore-R1/XDJRX.UPD: ' + s.out.r1.length + ' bytes, md5 ' + XRM.hash.md5(s.out.r1));
			}],
			['Building emergency file R2', () => {
				s.out.r2 = r2(s, opts && opts.r2Release || '2.22');
				note('emergency-R2/XDJRX.UPD (release ' + s.r2Release + '): ' + s.out.r2.length + ' bytes, md5 ' + XRM.hash.md5(s.out.r2));
			}],
			['Comparing with the published build', () => {
				const e = A().expected || {};
				s.match = {};
				for (const k of ['install', 'r1']) s.match[k] = e[k] ? XRM.hash.md5(s.out[k]) === e[k] : null;
				const er2 = e.r2 && e.r2[s.r2Release];
				s.match.r2 = er2 ? XRM.hash.md5(s.out.r2) === er2 : null;
				note('same as the published build: install ' + s.match.install + ', R1 ' + s.match.r1 + ', R2 ' + s.match.r2);
			}],
		].map(([label, fn]) => ({ label, run: fn, state: s }));
	}

	function r2(s, release) {
		if (!/^2\.\d\d$/.test(release) || !(parseFloat(release) > 2.21)) fail('R2 release must look like 2.22 and be above 2.21');
		const f = s.files['/images/release.txt'];
		if (!f) fail('the update holds no release.txt');
		const old = XRM.hash.text(s.read(f.extent * 2048, f.size));
		if (old !== PIONEER.release) fail('unexpected release.txt');
		s.r2Release = release;
		return XRM.upd.patch(s.keys, s.upd, f.extent * 2048, asc(release + '\n'));
	}

	function rebuildR2(state, release) {	// for the page's R2 version field
		state.out.r2 = r2(state, release);
		state.log.push('emergency-R2/XDJRX.UPD rebuilt (release ' + release + '): md5 ' + XRM.hash.md5(state.out.r2));
		const e = (A().expected || {}).r2 || {};
		state.match.r2 = e[release] ? XRM.hash.md5(state.out.r2) === e[release] : null;
		return state.out.r2;
	}

	function run(input, opts, progress) {	// synchronous (tests)
		const list = steps(input, opts);
		for (const st of list) { if (progress) progress(st.label); st.run(); }
		return list[0].state;
	}

	function readme(state) {
		const r = A().release;
		return asc(A().readme.replace(/\{name\}/g, r.name).replace(/\{r2\}/g, state.r2Release)
			.replace(/\{md5_install\}/g, XRM.hash.md5(state.out.install)).replace(/\{md5_r1\}/g, XRM.hash.md5(state.out.r1))
			.replace(/\{md5_r2\}/g, XRM.hash.md5(state.out.r2)).replace(/\r?\n/g, '\r\n'));
	}

	function zipAll(state) {
		return XRM.zip.store([
			{ name: 'README-FIRST.txt', data: readme(state) },
			{ name: 'install/XDJRX.UPD', data: state.out.install },
			{ name: 'restore-R1/XDJRX.UPD', data: state.out.r1 },
			{ name: 'emergency-R2/XDJRX.UPD', data: state.out.r2 },
			{ name: 'build-log.txt', data: asc(state.log.join('\r\n') + '\r\n') },
		]);
	}

	return { PIONEER, GPL_READ, HEAD_BYTES, identify, firmware, key, steps, run, rebuildR2, readme, zipAll };
})();
